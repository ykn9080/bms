#!/bin/bash

# ==========================================
# 사용자 설정 변수
# ==========================================
KEY_FILE="aws_certs/ec2.pem"
TARGET_USER="ec2-user"                # 원격 서버 접속 계정
TARGET_HOST="3.39.25.21"           # 원격 서버 IP 또는 도메인
TARGET_DIR="/home/ec2-user/"  # 원격 서버 저장 경로 (미리 생성되어 있어야 함)
SSH_PORT="22"                         # SSH 포트 (기본값: 22)

# ==========================================
# 2. 파일 권한 체크 및 전송 실행
# ==========================================
# .pem 키 파일의 권한이 너무 열려있으면 scp가 거부되므로 400으로 제한
chmod 400 "$KEY_FILE" 2>/dev/null

# ==========================================
# 전송 실행
# ==========================================
echo "현재 디렉토리의 모든 내용(숨김 파일 포함)을 전송합니다..."

# -i: .pem 키 파일 지정
# -P: SSH 포트 지정
# -r: 하위 디렉토리 포함 복사
scp -i "$KEY_FILE" -P $SSH_PORT -r . "$EC2_USER@$EC2_HOST:$TARGET_DIR"

#scp -i "aws_certs/ec2.pem" -p 22 -r . "ec2-user@3.39.25.21:/home/ec2-user"
# 결과 확인
if [ $? -eq 0 ]; then
    echo "✅ 모든 파일이 성공적으로 전송되었습니다!"
else
    echo "❌ 전송 중 오류가 발생했습니다."
fi
